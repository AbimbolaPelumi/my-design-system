import StyleDictionary from 'style-dictionary'
import { promises as fs } from 'fs'

// ─── Custom transforms ────────────────────────────────────────────────────────

StyleDictionary.registerTransform({
    name: 'size/pxToRem',
    type: 'value',
    filter: (token) =>
        token.$type === 'number' &&
        token.path.some((p) => p === 'size'),
    transform: (token) => `${token.$value / 16}rem`,
})

StyleDictionary.registerTransform({
    name: 'size/px',
    type: 'value',
    filter: (token) =>
        token.$type === 'number' &&
        !token.path.some((p) => p === 'size') &&
        !token.path.some((p) => p === 'weight') &&
        !token.path.some((p) => p === 'family'),
    transform: (token) => {
        if (token.$value === 0) return '0'
        return `${token.$value}px`
    },
})

StyleDictionary.registerTransform({
    name: 'name/commaToHyphen',
    type: 'name',
    transform: (token) => {
      const name = token.path.join('-').replace(/,/g, '-')
      const prefixed = /^\d/.test(name) ? `size-${name}` : name
      return `k-${prefixed}`
    },
})

// ─── Transform groups ─────────────────────────────────────────────────────────

StyleDictionary.registerTransformGroup({
  name: 'kuda/css',
  transforms: [
    'name/commaToHyphen',
    'size/pxToRem',
    'size/px',
    'color/css',
  ],
})

